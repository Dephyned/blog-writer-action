#!/usr/bin/env node

/**
 * Build step: reads the markdown prompts in prompts/ and inlines each into
 * a src/*-prompt.js module export so ncc can bundle them.
 */

const fs = require('fs');
const path = require('path');

const PROMPTS = [
  { source: 'default-blog-post.md', output: 'default-prompt.js', exportName: 'DEFAULT_PROMPT_TEMPLATE' },
  { source: 'setup.md', output: 'setup-prompt-template.js', exportName: 'SETUP_PROMPT_TEMPLATE' },
  { source: 'brief.md', output: 'brief-prompt-template.js', exportName: 'BRIEF_PROMPT_TEMPLATE' },
  { source: 'fix-build.md', output: 'fix-build-prompt-template.js', exportName: 'FIX_BUILD_PROMPT_TEMPLATE' },
  { source: 'fix-post.md', output: 'fix-post-prompt-template.js', exportName: 'FIX_POST_PROMPT_TEMPLATE' },
];

for (const { source, output, exportName } of PROMPTS) {
  const promptPath = path.join(__dirname, '..', 'prompts', source);
  const outputPath = path.join(__dirname, '..', 'src', output);

  const template = fs.readFileSync(promptPath, 'utf8');

  // Escape backticks and dollar-braces for embedding in a JS template literal
  const escaped = template.replace(/\\/g, '\\\\').replace(/`/g, '\\`').replace(/\$\{/g, '\\${');

  const contents = `// Auto-generated by scripts/embed-prompt.js — do not edit manually
const ${exportName} = \`${escaped}\`;

module.exports = { ${exportName} };
`;

  fs.writeFileSync(outputPath, contents, 'utf8');
  console.log('Embedded', source, 'into', outputPath);
}
