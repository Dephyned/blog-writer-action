#!/usr/bin/env node

/**
 * Build step: reads prompts/default-blog-post.md and inlines it into
 * src/default-prompt.js as a module export so ncc can bundle it.
 */

const fs = require('fs');
const path = require('path');

const PROMPT_PATH = path.join(__dirname, '..', 'prompts', 'default-blog-post.md');
const OUTPUT_PATH = path.join(__dirname, '..', 'src', 'default-prompt.js');

const template = fs.readFileSync(PROMPT_PATH, 'utf8');

// Escape backticks and dollar-braces for embedding in a JS template literal
const escaped = template.replace(/\\/g, '\\\\').replace(/`/g, '\\`').replace(/\$\{/g, '\\${');

const output = `// Auto-generated by scripts/embed-prompt.js — do not edit manually
const DEFAULT_PROMPT_TEMPLATE = \`${escaped}\`;

module.exports = { DEFAULT_PROMPT_TEMPLATE };
`;

fs.writeFileSync(OUTPUT_PATH, output, 'utf8');
console.log('Embedded default prompt template into', OUTPUT_PATH);
